import assert from 'node:assert/strict';
import {shouldCheckCovering,coveringEstimate} from '../web/app/covering-policy.js';
const base={mode:'auto',phase:'generation',count:1000,order:24,age:1,elapsed:1000,stepMilliseconds:5,model:null};
assert(shouldCheckCovering(base));
assert(!shouldCheckCovering({...base,count:1000000}));
assert(shouldCheckCovering({...base,count:10000}));
assert(!shouldCheckCovering({...base,count:12000}));
assert(shouldCheckCovering({...base,count:12000,model:{milliseconds:80,count:12000,order:24}}));
assert(!shouldCheckCovering({...base,count:1000000,model:{milliseconds:3000,count:1000000,order:24}}));
assert(shouldCheckCovering({...base,count:10000,phase:'step',age:30,model:{milliseconds:25,count:10000,order:24}}));
assert(!shouldCheckCovering({...base,model:{milliseconds:3000,count:1000,order:24}}));
assert(shouldCheckCovering({...base,model:{milliseconds:3000,count:1000,order:24,cold:true}}));
assert(!shouldCheckCovering({...base,phase:'step',age:1000,elapsed:100000,model:{milliseconds:500,count:1000,order:24}}));
assert(shouldCheckCovering({...base,phase:'end',model:{milliseconds:500,count:1000,order:24}}));
assert(!shouldCheckCovering({...base,phase:'step',age:10,elapsed:50}));
assert(shouldCheckCovering({...base,phase:'step',age:100,elapsed:1500,model:{milliseconds:100,count:1000,order:24}}));
assert(!shouldCheckCovering({...base,mode:'manual',phase:'end'}));
assert(shouldCheckCovering({...base,mode:'end',phase:'end',count:1000000}));
assert(!shouldCheckCovering({...base,mode:'end',phase:'step'}));
assert(shouldCheckCovering({...base,mode:'ten',phase:'step',age:10}));
assert(!shouldCheckCovering({...base,mode:'ten',phase:'step',age:9}));
assert(!shouldCheckCovering({...base,failed:true}));
assert(coveringEstimate(10000,60,{milliseconds:100,count:1000,order:24})>1000);
console.log('Covering update policy: small/large, measured latency, run-end, manual, explicit cadence, failure backoff passed.');
